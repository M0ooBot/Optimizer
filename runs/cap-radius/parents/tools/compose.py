"""Write each analytic parent.py from the shared jet code and one shape source."""

import re
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
PARENTS = TOOLS.parent

# (folder, shape source, reach) for the analytic parents.
ANALYTIC = [
    ("flat", "flat", None),
    ("twisted", "twisted", None),
    ("swept55", "swept55", None),
    ("fin40", "fin", 40.0),
    ("fin5", "fin", 5.0),
]
VARIANTS = {"sharp": 0.0, "blunt": 0.4}

HEADER = '''{doc}

Variant: {variant}. {variant_text}

Generated by runs/cap-radius/parents/tools/compose.py; do not edit by hand.
Lengths are millimetres. Needs NumPy only.

Main functions
--------------
skin_jet(s, span, side)  point and exact first and second derivatives with
                         respect to the chord parameter s (0 at the leading
                         edge, 1 at the trailing-edge end of that skin) and
                         the span station (Y for wings, Z for fins)
skin(s, span, side)      points only
te_face_jet / te_face    the flat trailing-edge face (blunt variant only)
cut(span)                where the keep-chord cut lands at a station
section_frame(span)      2D section frame (origin = leading-edge point)
section_thickness(xi, span)
                         finished section thickness at chord fraction xi
tip_outline / tip_outline_jet
                         the locked tip outline
ATTACHMENT, SPAN_LIMITS, AXES, UNITS, REACH, TE_THICKNESS, OUTLINE
"""

import numpy as np

'''

SHARP_TEXT = "The parent exactly as accepted; the trailing edge closes to a point."
BLUNT_TEXT = ("The trailing edge is blunted with the Airfoil Converter rule 'TE thickness' "
              "0.4 mm with 'Keep chord after the cut': at every span station the section is cut "
              "where the finished section is 0.4 mm thick (perpendicular to the chord), then "
              "scaled uniformly about its leading-edge point (the 2D origin) so the chord is kept. "
              "The trailing edge is a flat face 0.4 mm thick along the whole span.")


def compose(folder, shape, reach, variant):
    source = (TOOLS / "shapes" / f"{shape}.py").read_text(encoding="utf-8")
    match = re.match(r'"""(.*?)"""\n', source, re.S)
    doc, body = match.group(1), source[match.end():]
    body = re.sub(r'^VARIANT = "sharp"$', f'VARIANT = "{variant}"', body, count=1, flags=re.M)
    body = re.sub(r"^TE_THICKNESS = 0\.0$", f"TE_THICKNESS = {VARIANTS[variant]!r}", body, count=1, flags=re.M)
    if reach is not None:
        body, n = re.subn(r"^REACH = 40\.0$", f"REACH = {reach!r}", body, count=1, flags=re.M)
        assert n == 1
    body = re.sub(r'^SHAPE = "fin"$', f'SHAPE = "{folder}"', body, count=1, flags=re.M)
    jet = (TOOLS / "jet.py").read_text(encoding="utf-8")
    text = '"""' + HEADER.format(doc=doc.strip(), variant=variant,
                                variant_text=SHARP_TEXT if variant == "sharp" else BLUNT_TEXT) \
        + jet + "\n\n" + body
    out = PARENTS / folder / variant / "parent.py"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    return out


def main():
    for folder, shape, reach in ANALYTIC:
        for variant in VARIANTS:
            print(compose(folder, shape, reach, variant))


if __name__ == "__main__":
    main()
