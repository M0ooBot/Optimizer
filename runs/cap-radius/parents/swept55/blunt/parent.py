"""Symmetric 55-degree swept, tapered wing with a NACA 0009 closed-TE section (accepted swept55 trial).

Native chord parameter q in [0, 1], chord fraction U = 3q^2 - 2q^3, half
thickness per chord t = 0.45 (0.2969 q sqrt(3 - 2q) - 0.1260 U - 0.3516 U^2
+ 0.2843 U^3 - 0.1036 U^4) (q sqrt(3 - 2q) = sqrt(U)). Leading edge at
X = tan(55 deg) |Y|, Z = 0; chord 210 - (115/390) |Y| mm. Level and untwisted.

Variant: blunt. The trailing edge is blunted with the Airfoil Converter rule 'TE thickness' 0.4 mm with 'Keep chord after the cut': at every span station the section is cut where the finished section is 0.4 mm thick (perpendicular to the chord), then scaled uniformly about its leading-edge point (the 2D origin) so the chord is kept. The trailing edge is a flat face 0.4 mm thick along the whole span.

Generated by runs/cap-radius/parents/tools/compose.py; do not edit by hand.
Lengths are millimetres. Needs NumPy only.

Main functions
--------------
skin_jet(s, span, side)  point and exact first and second derivatives with
                         respect to the chord parameter s (0 at the leading
                         edge, 1 at the trailing-edge end of that skin) and
                         the span station (Y for wings, Z for fins)
skin(s, span, side)      points only
te_face_jet / te_face    the flat trailing-edge face (blunt variant only)
cut(span)                where the keep-chord cut lands at a station
section_frame(span)      2D section frame (origin = leading-edge point)
section_thickness(xi, span)
                         finished section thickness at chord fraction xi
tip_outline / tip_outline_jet
                         the locked tip outline
ATTACHMENT, SPAN_LIMITS, AXES, UNITS, REACH, TE_THICKNESS, OUTLINE
"""

import numpy as np

# ---------------------------------------------------------------------------
# Second-order forward differentiation (NumPy only).
#
# A Jet carries a value together with its exact first and second partial
# derivatives with respect to n seed variables. Derivative axes are trailing:
# d has shape value.shape + (n,), h has shape value.shape + (n, n).
# ---------------------------------------------------------------------------


class Jet:
    __array_priority__ = 1000
    __slots__ = ("v", "d", "h")

    def __init__(self, v, d, h):
        self.v, self.d, self.h = v, d, h

    @property
    def n(self):
        return self.d.shape[-1]

    @classmethod
    def variable(cls, value, index, n):
        v = np.array(value, dtype=float)
        d = np.zeros(v.shape + (n,))
        d[..., index] = 1.0
        return cls(v, d, np.zeros(v.shape + (n, n)))

    @classmethod
    def constant(cls, value, n):
        v = np.array(value, dtype=float)
        return cls(v, np.zeros(v.shape + (n,)), np.zeros(v.shape + (n, n)))

    def _lift(self, other):
        return other if isinstance(other, Jet) else Jet.constant(other, self.n)

    def chain(self, f0, f1, f2):
        """Compose with a scalar function given its value and first two derivatives."""
        f1 = np.asarray(f1, dtype=float)
        f2 = np.asarray(f2, dtype=float)
        d = self.d
        return Jet(np.asarray(f0, dtype=float), f1[..., None] * d,
                   f1[..., None, None] * self.h + f2[..., None, None] * d[..., :, None] * d[..., None, :])

    def __add__(self, other):
        other = self._lift(other)
        return Jet(self.v + other.v, self.d + other.d, self.h + other.h)

    __radd__ = __add__

    def __neg__(self):
        return Jet(-self.v, -self.d, -self.h)

    def __sub__(self, other):
        return self + (-self._lift(other))

    def __rsub__(self, other):
        return self._lift(other) - self

    def __mul__(self, other):
        if not isinstance(other, Jet):
            c = np.asarray(other, dtype=float)
            return Jet(self.v * c, self.d * c[..., None], self.h * c[..., None, None])
        a, b = self, other
        return Jet(
            a.v * b.v,
            a.d * b.v[..., None] + b.d * a.v[..., None],
            a.h * b.v[..., None, None] + b.h * a.v[..., None, None]
            + a.d[..., :, None] * b.d[..., None, :] + b.d[..., :, None] * a.d[..., None, :],
        )

    __rmul__ = __mul__

    def reciprocal(self):
        v = self.v
        return self.chain(1.0 / v, -1.0 / v**2, 2.0 / v**3)

    def __truediv__(self, other):
        if not isinstance(other, Jet):
            return self * (1.0 / np.asarray(other, dtype=float))
        return self * other.reciprocal()

    def __rtruediv__(self, other):
        return self.reciprocal() * other

    def __pow__(self, p):
        if not isinstance(p, int) or p < 0:
            raise ValueError("Jet powers take non-negative integers; use jsqrt for roots")
        v = self.v
        f1 = p * v ** (p - 1) if p >= 1 else np.zeros_like(v)
        f2 = p * (p - 1) * v ** (p - 2) if p >= 2 else np.zeros_like(v)
        return self.chain(v**p, f1, f2)


def jsin(x):
    return x.chain(np.sin(x.v), np.cos(x.v), -np.sin(x.v))


def jcos(x):
    return x.chain(np.cos(x.v), -np.sin(x.v), -np.cos(x.v))


def jsqrt(x):
    r = np.sqrt(x.v)
    return x.chain(r, 0.5 / r, -0.25 / (r * x.v))


def jarccos(x):
    w = np.sqrt(1.0 - x.v**2)
    return x.chain(np.arccos(x.v), -1.0 / w, -x.v / w**3)


def jabs(x):
    """|x| with the derivative of the positive branch at x = 0 (one-sided at a mirror plane)."""
    sign = np.where(x.v < 0, -1.0, 1.0)
    return x * sign


def jwhere(condition, a, b):
    condition = np.asarray(condition)
    return Jet(np.where(condition, a.v, b.v), np.where(condition[..., None], a.d, b.d),
               np.where(condition[..., None, None], a.h, b.h))


def _seed(chord, span):
    """Seed the two surface variables: index 0 is the chord parameter, index 1 the span station."""
    chord, span = np.broadcast_arrays(np.asarray(chord, float), np.asarray(span, float))
    return Jet.variable(chord, 0, 2), Jet.variable(span, 1, 2)


def _const(value, like):
    return Jet.constant(np.broadcast_to(np.asarray(value, float), like.v.shape), like.n)


def _pack(xyz, chord_name="chord", span_name="span"):
    """Turn three coordinate jets into point and derivative arrays (last axis = XYZ)."""
    shape = np.broadcast_shapes(*(c.v.shape for c in xyz))
    xyz = [Jet(np.broadcast_to(c.v, shape), np.broadcast_to(c.d, shape + (2,)),
               np.broadcast_to(c.h, shape + (2, 2))) for c in xyz]
    stack = lambda f: np.stack([f(c) for c in xyz], axis=-1)
    return {
        "point": stack(lambda c: c.v),
        f"d_{chord_name}": stack(lambda c: c.d[..., 0]),
        f"d_{span_name}": stack(lambda c: c.d[..., 1]),
        f"d_{chord_name}_{chord_name}": stack(lambda c: c.h[..., 0, 0]),
        f"d_{chord_name}_{span_name}": stack(lambda c: c.h[..., 0, 1]),
        f"d_{span_name}_{span_name}": stack(lambda c: c.h[..., 1, 1]),
    }


def _pack1(xyz):
    """Point and derivatives of a curve seeded with one variable p."""
    shape = np.broadcast_shapes(*(c.v.shape for c in xyz))
    stack = lambda f: np.stack([np.broadcast_to(f(c), shape) for c in xyz], axis=-1)
    return {"point": stack(lambda c: c.v), "d_p": stack(lambda c: c.d[..., 0]),
            "d_p_p": stack(lambda c: c.h[..., 0, 0])}


def _bisect(function, lo, hi, iterations=200):
    """Vectorised bisection for a sign change of function between lo and hi."""
    lo = np.array(lo, dtype=float)
    hi = np.array(hi, dtype=float)
    lo, hi = np.broadcast_arrays(lo, hi)
    lo, hi = lo.copy(), hi.copy()
    f_lo = function(lo)
    for _ in range(iterations):
        mid = 0.5 * (lo + hi)
        f_mid = function(mid)
        left = np.sign(f_mid) == np.sign(f_lo)
        lo = np.where(left, mid, lo)
        f_lo = np.where(left, f_mid, f_lo)
        hi = np.where(left, hi, mid)
        if np.all(hi - lo <= 4e-16 * np.maximum(1.0, np.abs(hi))):
            break
    return 0.5 * (lo + hi)


def _implicit(residual, roots, outer):
    """Exact first and second derivatives of implicitly defined unknowns.

    residual(unknowns, outer) returns k residual jets for k unknown jets. roots
    are the solved values. The unknowns depend on the outer jet only; the
    result is expressed in the outer jet's seed variables (implicit function
    theorem through second order).
    """
    k = len(roots)
    shape = np.broadcast_shapes(outer.v.shape, *(np.shape(r) for r in roots))
    unknowns = [Jet.variable(np.broadcast_to(r, shape), i, k + 1) for i, r in enumerate(roots)]
    seed = Jet.variable(np.broadcast_to(outer.v, shape), k, k + 1)
    res = residual(unknowns, seed)
    jac = np.stack([np.stack([r.d[..., j] for j in range(k)], -1) for r in res], -2)
    r_y = np.stack([r.d[..., k] for r in res], -1)
    r_uu = np.stack([r.h[..., :k, :k] for r in res], -3)
    r_uy = np.stack([r.h[..., :k, k] for r in res], -2)
    r_yy = np.stack([r.h[..., k, k] for r in res], -1)
    first = -np.linalg.solve(jac, r_y[..., None])[..., 0]
    rhs = r_yy + 2 * np.einsum("...ij,...j->...i", r_uy, first) \
        + np.einsum("...ijl,...j,...l->...i", r_uu, first, first)
    second = -np.linalg.solve(jac, rhs[..., None])[..., 0]
    od = np.broadcast_to(outer.d, shape + (outer.n,))
    oh = np.broadcast_to(outer.h, shape + (outer.n, outer.n))
    return [Jet(np.broadcast_to(np.asarray(r, float), shape).copy(),
                first[..., i, None] * od,
                first[..., i, None, None] * oh + second[..., i, None, None] * od[..., :, None] * od[..., None, :])
            for i, r in enumerate(roots)]


def _newton_polish(residual, roots, outer_value, steps=4):
    """Polish real roots of residual(unknowns, outer) with Newton steps (k unknowns)."""
    k = len(roots)
    roots = [np.array(r, dtype=float) for r in roots]
    for _ in range(steps):
        shape = np.broadcast_shapes(np.shape(outer_value), *(np.shape(r) for r in roots))
        unknowns = [Jet.variable(np.broadcast_to(r, shape), i, k) for i, r in enumerate(roots)]
        outer = Jet.constant(np.broadcast_to(outer_value, shape), k)
        res = residual(unknowns, outer)
        jac = np.stack([np.stack([r.d[..., j] for j in range(k)], -1) for r in res], -2)
        value = np.stack([r.v for r in res], -1)
        step = np.linalg.solve(jac, value[..., None])[..., 0]
        roots = [np.broadcast_to(r, shape) - step[..., i] for i, r in enumerate(roots)]
    return roots



SHAPE = "swept55"
VARIANT = "blunt"
TE_THICKNESS = 0.4
UNITS = "mm"
AXES = {"X": "aft, along the chord", "Y": "span (+Y is the right tip)", "Z": "up"}
SPAN_AXIS = "Y"
SIDES = {+1: "upper (+Z)", -1: "lower (-Z)"}
ATTACHMENT = 390.0
SPAN_LIMITS = (-ATTACHMENT, ATTACHMENT)
FULL_SPAN = True
ROOT_CHORD = 210.0
TAPER = 115.0 / ATTACHMENT
SWEEP = float(np.tan(np.radians(55.0)))
REACH = 60.0


def _U(q):
    return q * q * (3 - 2 * q)


def _t(q):
    u = _U(q)
    return 0.45 * (0.2969 * q * jsqrt(3 - 2 * q) - 0.1260 * u - 0.3516 * u * u
                   + 0.2843 * u * u * u - 0.1036 * u * u * u * u)


def chord(span):
    return ROOT_CHORD - TAPER * np.abs(np.asarray(span, float))


def _cut(span):
    if TE_THICKNESS == 0:
        return _const(1.0, span), _const(1.0, span)

    def residual(unknowns, outer):
        q = unknowns[0]
        c = ROOT_CHORD - TAPER * jabs(outer)
        return [2 * c * _t(q) / _U(q) - TE_THICKNESS]

    c = ROOT_CHORD - TAPER * np.abs(span.v)

    def real(q):
        j = Jet.constant(q, 0)
        return 2 * c * (_t(j) / _U(j)).v - TE_THICKNESS

    root = _bisect(real, np.full(span.v.shape, 0.6), np.full(span.v.shape, 1.0))
    root = _newton_polish(residual, [root], span.v)
    q_end, = _implicit(residual, root, span)
    return q_end, 1 / _U(q_end)


def cut(span):
    q_end, scale = _cut(Jet.constant(span, 2))
    return {"q_end": q_end.v, "cut_chord_fraction": _U(q_end).v, "scale": scale.v}


def _skin(s, span, side):
    q_end, scale = _cut(span)
    q = s * q_end
    ya = jabs(span)
    c = ROOT_CHORD - TAPER * ya
    return [SWEEP * ya + c * scale * _U(q), span + 0 * q, side * c * scale * _t(q)]


def skin_jet(s, span, side):
    """Skin point and exact derivatives at chord parameter s (0 = LE, 1 = TE end) and Y = span.

    side +1 is the upper skin, -1 the lower. |Y| enters the planform, so at
    Y = 0 the span derivatives are those of the right (+Y) half. Returns a dict
    of arrays (last axis XYZ): point, d_chord, d_span, d_chord_chord,
    d_chord_span, d_span_span.
    """
    sj, yj = _seed(s, span)
    return _pack(_skin(sj, yj, side))


def skin(s, span, side):
    return skin_jet(s, span, side)["point"]


def te_face_jet(t, span):
    """Blunt trailing-edge face: t = 0 on the lower TE corner, t = 1 on the upper corner."""
    if TE_THICKNESS == 0:
        raise ValueError("The sharp variant has no trailing-edge face")
    tj, yj = _seed(t, span)
    one = _const(1.0, tj)
    upper, lower = _skin(one, yj, +1), _skin(one, yj, -1)
    return _pack([lo + tj * (up - lo) for up, lo in zip(upper, lower)], "t", "span")


def te_face(t, span):
    return te_face_jet(t, span)["point"]


def section_frame(span):
    span = float(span)
    return {"origin": np.array([SWEEP * abs(span), span, 0.0]), "chord_direction": np.array([1.0, 0, 0]),
            "up_direction": np.array([0, 0, 1.0]), "chord": float(chord(span))}


def section_thickness(xi, span):
    """Thickness in mm across the finished section at chord fraction xi (vertical in the section)."""
    xi, span = np.broadcast_arrays(np.asarray(xi, float), np.asarray(span, float))
    q_end, scale = _cut(Jet.constant(span, 0))
    target = xi / scale.v
    q = _bisect(lambda q: _U(Jet.constant(q, 0)).v - target, np.zeros_like(target), np.ones_like(target))
    q = np.where(target >= _U(q_end).v, q_end.v, q)
    thickness = 2 * chord(span) * scale.v * _t(Jet.constant(q, 0)).v
    return np.where(target <= _U(q_end).v * (1 + 1e-12), thickness, np.nan)


def tip_outline_jet(p, side=+1):
    """Locked plan outline (lip) at Z = 0, p = 0 at the LE end, 1 at the TE end.

    The lip lies on the parent planform continued outboard: at station
    r = 390 + 240 p (1 - p) it sits at chord fraction U(p) = 3p^2 - 2p^3,
    X = tan(55 deg) r + (210 - (115/390) r) U(p).
    """
    pj = Jet.variable(np.asarray(p, float), 0, 1)
    r = ATTACHMENT + 240 * pj * (1 - pj)
    xyz = [SWEEP * r + (ROOT_CHORD - TAPER * r) * _U(pj), side * r, 0 * pj]
    return _pack1(xyz)


def tip_outline(p, side=+1):
    return tip_outline_jet(p, side)["point"]


